"""
Generates example xlsx files for manual UI testing of the «Обработка» page.

Three scenarios are produced — each in its own subfolder:
  examples/leader_smi/   — UPD scenario (advertising)
  examples/veneta/        — UPD scenario (printer cartridges)
  examples/dlux/          — Act scenario (car wash, with discount + coefficient)

Run from project root:
  python examples/_generate_examples.py

Requires openpyxl (already in backend deps).
"""
from pathlib import Path

from openpyxl import Workbook

ROOT = Path(__file__).resolve().parent


def save(wb: Workbook, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(path))
    wb.close()
    print(f"  + {path.relative_to(ROOT.parent)}")


def _write_price_sheet(wb: Workbook, title: str, header_lines: list[str], rows: list[tuple]) -> None:
    """Заполняет первый лист стандартной шапкой и таблицей (№, Наименование, Ед., Цена)."""
    ws = wb.active
    ws.title = title
    for line in header_lines:
        ws.append([line])
    ws.append([])
    ws.append(["№", "Наименование услуги", "Единица измерения", "Цена за единицу с НДС, руб."])
    for row in rows:
        ws.append(list(row))


def _write_upd_sheet(wb: Workbook, header_lines: list[str], rows: list[tuple]) -> None:
    """Заполняет лист УПД стандартной шапкой и таблицей (№, Наименование, Кол-во, Ед., Сумма)."""
    ws = wb.active
    ws.title = "УПД"
    for line in header_lines:
        ws.append([line])
    ws.append([])
    ws.append(["№", "Наименование услуги", "Количество", "Единица измерения", "Сумма"])
    for row in rows:
        ws.append(list(row))


